-- Battery Stock Register & WhatsApp Dispatcher
-- Initial Supabase PostgreSQL Schema Migration
-- Run via: supabase db push (after supabase link --project-ref anaibpuhnxlwfeypprlb)
-- Or paste into Supabase Dashboard -> SQL Editor

CREATE TABLE IF NOT EXISTS public.stock_records (
  date VARCHAR(50) PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.battery_metadata (
  key VARCHAR(50) PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.battery_serials (
  serial_no VARCHAR(100) PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action VARCHAR(100) NOT NULL,
  details JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_stock_records_updated_at
  ON public.stock_records (updated_at DESC);

CREATE INDEX IF NOT EXISTS idx_battery_serials_updated_at
  ON public.battery_serials (updated_at DESC);

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
  ON public.audit_logs (created_at DESC);

-- Enable Row Level Security (RLS)
-- The Express backend should authenticate with SUPABASE_SERVICE_ROLE_KEY
-- (or direct DATABASE_URL), which bypasses RLS safely on the server side.
ALTER TABLE public.stock_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.battery_metadata ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.battery_serials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_logs ENABLE ROW LEVEL SECURITY;

-- Service role policies (explicit)
DROP POLICY IF EXISTS "service_role_all_stock_records" ON public.stock_records;
CREATE POLICY "service_role_all_stock_records"
  ON public.stock_records
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

